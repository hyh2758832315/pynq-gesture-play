def configure_vga_yuv(bus: RegisterBus) -> None:
    chip_id = bus.read_ov5640_chip_id()
    if chip_id != 0x5640:
        raise RuntimeError(f"Unexpected OV5640 chip ID: 0x{chip_id:04X}")

    bus.write_register(SENSOR_ADDRESS, 0x3008, 0x42)
    bus.write_register(SENSOR_ADDRESS, 0x3103, 0x11)
    bus.write_register(SENSOR_ADDRESS, 0x3008, 0x82)
    time.sleep(0.005)
    bus.write_register(SENSOR_ADDRESS, 0x3103, 0x03)
    bus.write_register(SENSOR_ADDRESS, 0x3008, 0x42)
    for register, value in BASE_INITIALIZATION:
        bus.write_register(SENSOR_ADDRESS, register, value)
    for register, value in VGA_YUV_REGISTERS:
        bus.write_register(SENSOR_ADDRESS, register, value)

    for register, mask, bits in (
        (0x3820, 0x01, 0x01),
        (0x3821, 0x21, 0x01),
        (0x3002, 0x1C, 0x1C),
        (0x3006, 0x28, 0x00),
    ):
        old_value = bus.read_register(SENSOR_ADDRESS, register)
        bus.write_register(SENSOR_ADDRESS, register, (old_value & ~mask) | bits)

    for register in (
        0x3036, 0x3037, 0x3808, 0x3809, 0x380A, 0x380B,
        0x4300, 0x4602, 0x4603, 0x4604, 0x4605, 0x503D,
    ):
        expected = dict(VGA_YUV_REGISTERS)[register]
        actual = bus.read_register(SENSOR_ADDRESS, register)
        if actual != expected:
            raise RuntimeError(
                f"OV5640 register 0x{register:04X}: expected 0x{expected:02X}, got 0x{actual:02X}"
            )

    time.sleep(0.3)
    bus.write_register(SENSOR_ADDRESS, 0x3008, 0x02)
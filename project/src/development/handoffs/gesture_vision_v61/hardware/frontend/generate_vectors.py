"""Generate independent OpenCV goldens, reciprocal ROM, exhaustive model check.

PYNQ-Z2 / Vivado 2026.1. Run with NumPy/OpenCV Python before run_xsim.ps1.
Outputs rtl/hsv_reciprocal.svh, golden/*.hex, golden/summary.json.
Next: XSim backpressure/reset tests, then OOC synthesis; not board validated.
"""
import json
from pathlib import Path
import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent


def reciprocal(scale):
    a = np.zeros(256, np.int64)
    a[1:] = np.rint(scale / np.arange(1, 256)).astype(np.int64)
    return a


SD = reciprocal(255 * 4096)
HD = reciprocal(180 * 4096 / 6)


def integer_hsv(bgr):
    b, g, r = (bgr[..., i].astype(np.int64) for i in range(3))
    v = np.maximum(r, np.maximum(g, b))
    d = v - np.minimum(r, np.minimum(g, b))
    hn = np.where(v == r, g-b, np.where(v == g, b-r+2*d, r-g+4*d))
    h = (hn*HD[d]+2048) >> 12
    h = np.where(h < 0, h+180, h)
    s = (d*SD[v]+2048) >> 12
    return np.stack((h, s, v), axis=-1).astype(np.uint8)


def main():
    (ROOT / 'rtl').mkdir(exist_ok=True)
    (ROOT / 'golden').mkdir(exist_ok=True)
    lines = ['// Generated by generate_vectors.py; nearest-even, HSV shift=12.']
    for name, values, bits in [('sdiv', SD, 20), ('hdiv', HD, 17)]:
        lines += [f'function automatic [{bits-1}:0] {name}(input [7:0] a);',
                  '    begin case(a)']
        lines += [f"        8'd{i}: {name}={bits}'d{int(v)};" for i, v in enumerate(values)]
        lines += [f'        default: {name}=0;', '    endcase end', 'endfunction']
    (ROOT / 'rtl' / 'hsv_reciprocal.svh').write_text('\n'.join(lines)+'\n', encoding='ascii')

    # All 16,777,216 BGR colors, chunked to bound host memory. OpenCV is gold.
    colors_checked = 0
    idx = np.arange(65536, dtype=np.uint32)
    for r in range(256):
        a = np.empty((256, 256, 3), np.uint8)
        a[..., 0] = (idx & 255).reshape(256, 256)
        a[..., 1] = (idx >> 8).reshape(256, 256)
        a[..., 2] = r
        gold = cv2.cvtColor(a, cv2.COLOR_BGR2HSV)
        model = integer_hsv(a)
        if not np.array_equal(gold, model):
            bad = np.argwhere(gold != model)[0]
            raise AssertionError(f'OpenCV mismatch r={r} position={bad.tolist()}')
        colors_checked += 65536

    # RTL goldens: uniform gray, channel ties, dense sampled cube and random
    # 640x360 and 1280x720 frames. No inference based on annotated video pixels.
    rng = np.random.default_rng(20261005)
    gray = np.repeat(np.arange(256, dtype=np.uint8)[:, None], 3, axis=1)
    pair = np.indices((256, 256), dtype=np.uint16).reshape(2, -1).T.astype(np.uint8)
    ties = np.concatenate([pair[:, [0, 0, 1]], pair[:, [0, 1, 0]], pair[:, [1, 0, 0]]])
    cube = np.indices((32, 32, 32), dtype=np.uint16).reshape(3, -1).T.astype(np.uint8)*8
    frames = [np.concatenate([gray, ties, cube]),
              rng.integers(0, 256, (640*360, 3), dtype=np.uint8),
              rng.integers(0, 256, (1280*720, 3), dtype=np.uint8),
              rng.integers(0, 256, (1+2+3+7+31, 3), dtype=np.uint8)]
    a = np.concatenate(frames)
    hsv = cv2.cvtColor(a.reshape(-1, 1, 3), cv2.COLOR_BGR2HSV).reshape(-1, 3)
    # Change bounds every pixel to test that config travels through stalls.
    bounds = np.tile(np.array([0, 20, 20, 255, 70, 255], np.uint8), (len(a), 1))
    bounds[::4] = [0, 179, 0, 255, 0, 255]
    bounds[1::4] = np.repeat(hsv[1::4], 2, axis=1)  # inclusive exact H/S/V
    bounds[2::4] = [80, 100, 100, 200, 50, 240]
    mask = np.all((hsv >= bounds[:, ::2]) & (hsv <= bounds[:, 1::2]), axis=1)*255
    sof = np.zeros(len(a), np.uint64)
    last = np.zeros(len(a), np.uint64)
    pos = 0
    for n in [len(frames[0]), len(frames[1]), len(frames[2]), 1, 2, 3, 7, 31]:
        sof[pos] = 1
        last[pos+n-1] = 1
        pos += n
    assert pos == len(a)
    rgb_word = a[:, 0].astype(np.uint64) | (a[:, 1].astype(np.uint64)<<8) | (a[:, 2].astype(np.uint64)<<16)
    hsv_word = hsv[:, 0].astype(np.uint64) | (hsv[:, 1].astype(np.uint64)<<8) | (hsv[:, 2].astype(np.uint64)<<16)
    input_words = rgb_word | (sof<<24) | (last<<25)
    expected = hsv_word | (mask.astype(np.uint64)<<24) | (sof<<32) | (last<<33)
    bound_words = sum(bounds[:, i].astype(np.uint64) << (8*i) for i in range(6))
    for name, data, width in [('input', input_words, 8), ('expected', expected, 10), ('bounds', bound_words, 12)]:
        (ROOT/'golden'/f'{name}.hex').write_text(''.join(f'{int(x):0{width}x}\n' for x in data), encoding='ascii')
    summary = dict(opencv=cv2.__version__, exhaustive_model_colors=colors_checked,
                   rtl_pixels=len(a), rtl_frames=8, target='xc7z020clg400-1',
                   rtl_count_by_frame=[len(f) for f in frames[:3]]+[1,2,3,7,31],
                   status='model_only_until_xsim_and_board_tests')
    (ROOT/'golden'/'summary.json').write_text(json.dumps(summary, indent=2)+'\n', encoding='utf8')
    print('BGR_HSV_MODEL_GOLDEN_PASS', summary)


if __name__ == '__main__':
    main()
